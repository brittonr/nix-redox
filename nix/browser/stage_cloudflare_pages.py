#!/usr/bin/env python3
"""Stage a built browser-site tree for Cloudflare Pages (with R2 overflow for >25 MiB files)."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil

# Cloudflare Pages enforces a strict 25 MiB (26,214,400 bytes) per-file limit.
CLOUDFLARE_PAGES_MAX_FILE_BYTES = 25 * 1024 * 1024
CLOUDFLARE_ROUTES_MAX_RULES = 100

CONTENT_TYPES = {
    ".gz": "application/gzip",
    ".wasm": "application/wasm",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".xz": "application/x-xz",
    ".zst": "application/zstd",
    ".tar": "application/x-tar",
    ".bin": "application/octet-stream",
    ".rom": "application/octet-stream",
    ".fd": "application/octet-stream",
    ".img": "application/octet-stream",
}


def content_type_for(relpath):
    suffix = Path(relpath).suffix.lower()
    return CONTENT_TYPES.get(suffix, "application/octet-stream")


def immutable_path(url_path):
    return (
        re.search(r"/assets/[a-f0-9]{64}/", url_path) is not None
        or url_path.startswith("/revisions/")
    ) and not url_path.endswith("/coi-serviceworker.js")


def sha256_file(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


WORKER_JS = """// Generated by nix/browser/stage_cloudflare_pages.py.
// Serves only files exceeding Cloudflare Pages' 25 MiB per-file limit (routed via
// _routes.json) from the SITE_OVERFLOW R2 bucket binding, with the exact same
// COOP/COEP/CORP and Cache-Control contract as site/_headers and serve.py.
const CONTENT_TYPES = {
  ".gz": "application/gzip",
  ".wasm": "application/wasm",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".xz": "application/x-xz",
  ".zst": "application/zstd",
  ".tar": "application/x-tar",
};

function isImmutablePath(pathname) {
  return (
    (/\\/assets\\/[a-f0-9]{64}\\//.test(pathname) || pathname.startsWith("/revisions/")) &&
    !pathname.endsWith("/coi-serviceworker.js")
  );
}

function contentTypeFor(pathname) {
  const dot = pathname.lastIndexOf(".");
  if (dot >= 0) {
    const ext = pathname.slice(dot).toLowerCase();
    if (ext in CONTENT_TYPES) return CONTENT_TYPES[ext];
  }
  return "application/octet-stream";
}

function baseHeaders(pathname, status) {
  const headers = new Headers();
  headers.set("Cross-Origin-Opener-Policy", "same-origin");
  headers.set("Cross-Origin-Embedder-Policy", "require-corp");
  headers.set("Cross-Origin-Resource-Policy", "same-origin");
  headers.set("X-Content-Type-Options", "nosniff");
  headers.set(
    "Cache-Control",
    status >= 400
      ? "no-store"
      : isImmutablePath(pathname)
        ? "public, max-age=31536000, immutable"
        : "no-store"
  );
  return headers;
}

export default {
  async fetch(request, env) {
    if (request.method !== "GET" && request.method !== "HEAD") {
      const headers = baseHeaders("/", 405);
      headers.set("Allow", "GET, HEAD");
      return new Response("Method Not Allowed", { status: 405, headers });
    }
    const url = new URL(request.url);
    const pathname = url.pathname;
    if (!env.SITE_OVERFLOW) {
      return new Response(
        "SITE_OVERFLOW R2 binding is not configured on this Cloudflare Pages project.",
        { status: 503, headers: baseHeaders(pathname, 503) }
      );
    }
    const key = decodeURIComponent(pathname.replace(/^\\/+/, ""));
    if (!key || key.includes("..") || key.includes("\\0")) {
      return new Response("Bad Request", { status: 400, headers: baseHeaders(pathname, 400) });
    }
    const rangeHeader = request.headers.get("Range");
    const object =
      request.method === "HEAD"
        ? await env.SITE_OVERFLOW.head(key)
        : await env.SITE_OVERFLOW.get(key, rangeHeader ? { range: request.headers } : undefined);
    if (!object) {
      return new Response("Not Found", { status: 404, headers: baseHeaders(pathname, 404) });
    }
    const isPartial = Boolean(rangeHeader && object.range && request.method === "GET");
    const status = isPartial ? 206 : 200;
    const headers = baseHeaders(pathname, status);
    headers.set("Content-Type", object.httpMetadata?.contentType || contentTypeFor(pathname));
    headers.set("Accept-Ranges", "bytes");
    if (object.httpEtag) headers.set("ETag", object.httpEtag);
    if (isPartial) {
      const start = object.range.offset ?? 0;
      const length = object.range.length ?? object.size - start;
      const end = start + length - 1;
      headers.set("Content-Range", `bytes ${start}-${end}/${object.size}`);
      headers.set("Content-Length", String(length));
    } else {
      headers.set("Content-Length", String(object.size));
    }
    return new Response(request.method === "HEAD" ? null : object.body, { status, headers });
  },
};
"""


def stage(source_dir, out_dir, max_file_bytes=CLOUDFLARE_PAGES_MAX_FILE_BYTES):
    source = Path(source_dir).resolve(strict=True)
    out = Path(out_dir)
    if out.exists() and any(out.iterdir()):
        raise ValueError(f"staging output directory must be empty: {out}")
    pages_dir = out / "pages"
    overflow_dir = out / "r2-overflow"
    pages_dir.mkdir(parents=True, exist_ok=True)
    overflow_dir.mkdir(parents=True, exist_ok=True)

    total_files = 0
    pages_files = 0
    overflow_files = []

    for path in sorted(source.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(source).as_posix()
        size = path.stat().st_size
        total_files += 1
        if size > max_file_bytes:
            target = overflow_dir / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
            url_path = "/" + rel
            overflow_files.append(
                {
                    "key": rel,
                    "urlPath": url_path,
                    "size": size,
                    "sha256": sha256_file(path),
                    "contentType": content_type_for(rel),
                    "immutable": immutable_path(url_path),
                }
            )
        else:
            target = pages_dir / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
            pages_files += 1

    if overflow_files:
        if len(overflow_files) > CLOUDFLARE_ROUTES_MAX_RULES:
            raise ValueError(
                f"overflow file count ({len(overflow_files)}) exceeds Cloudflare Pages "
                f"_routes.json rule limit ({CLOUDFLARE_ROUTES_MAX_RULES})"
            )
        routes = {
            "version": 1,
            "include": [item["urlPath"] for item in overflow_files],
            "exclude": [],
        }
        (pages_dir / "_routes.json").write_text(
            json.dumps(routes, indent=2) + "\n", encoding="utf-8"
        )
        (pages_dir / "_worker.js").write_text(WORKER_JS, encoding="utf-8")

    summary = {
        "schemaVersion": 1,
        "maxFileBytes": max_file_bytes,
        "totalFiles": total_files,
        "pagesFiles": pages_files,
        "overflowCount": len(overflow_files),
        "r2BindingName": "SITE_OVERFLOW" if overflow_files else None,
        "overflowFiles": overflow_files,
    }
    (out / "staging-manifest.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return summary


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("source", help="built browser-site directory")
    p.add_argument("out", help="empty output staging directory")
    p.add_argument(
        "--max-file-bytes",
        type=int,
        default=CLOUDFLARE_PAGES_MAX_FILE_BYTES,
        help="per-file size threshold for Cloudflare Pages (default: 25 MiB)",
    )
    args = p.parse_args()
    summary = stage(args.source, args.out, args.max_file_bytes)
    print(
        f"Staged {summary['totalFiles']} files: "
        f"{summary['pagesFiles']} for Cloudflare Pages, "
        f"{summary['overflowCount']} for R2 overflow (> {summary['maxFileBytes']} bytes)."
    )


if __name__ == "__main__":
    main()
